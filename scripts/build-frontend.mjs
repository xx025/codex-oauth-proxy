import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "src/ui.generated.ts");
const result = await build({ entryPoints: [resolve(root, "frontend/app.tsx")], bundle: true, format: "esm", minify: true, charset: "utf8", outdir: "out", write: false, jsx: "automatic", jsxImportSource: "preact", legalComments: "none" });
const js = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
const css = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text;
if (!js || !css) throw new Error("esbuild did not emit both frontend assets");
const generated = `// Generated by scripts/build-frontend.mjs. Do not edit.\nexport const ADMIN_JS = ${JSON.stringify(js)};\nexport const ADMIN_CSS = ${JSON.stringify(css)};\n`;
await writeFile(output, generated);
