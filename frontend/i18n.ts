const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  en,
  "zh-CN": zh,
};

export function resolveLocale(
  preference: LanguagePreference,
  browserLanguages: readonly string[] = [],
): Locale {
  if (preference !== "system") return preference;
  return browserLanguages[0]?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function parseLanguagePreference(
  value: string | null,
): LanguagePreference {
  return value === "zh-CN" || value === "en" || value === "system"
    ? value
    : "system";
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

type I18nValue = {
  locale: Locale;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
};
const I18nContext = createContext<I18nValue>({
  locale: "en",
  t: (key, values) => translate("en", key, values),
});

export function I18nProvider({
  locale,
  children,
}: {
  locale: Locale;
  children: ComponentChildren;
}) {
  return createElement(
    I18nContext.Provider,
    {
      value: {
        locale,
        t: (key, values) => translate(locale, key, values),
      },
    },
    children,
  );
}

export const useI18n = () => useContext(I18nContext);
export const formatNumber = (locale: Locale, value: unknown) =>
  new Intl.NumberFormat(locale, {
    notation: Number(value) >= 1_000_000 ? "compact" : "standard",
    maximumFractionDigits: 1,
  }).format(Number(value) || 0);
export const formatDate = (locale: Locale, value: unknown) =>
  value
    ? new Intl.DateTimeFormat(locale, {
        dateStyle: "medium",
        timeStyle: "short",
      }).format(new Date(value as string | number))
    : "—";
export const formatPercent = (locale: Locale, value: number) =>
  new Intl.NumberFormat(locale, {
    style: "percent",
    maximumFractionDigits: 1,
  }).format(value);
